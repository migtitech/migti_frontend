/**
 * Sample data for the Procurement Requests screen (PurchaseTasks) and its
 * per-product detail view (PurchaseTaskDetail). Used purely for UI preview
 * when the backend list endpoints return nothing — not wired to the API.
 *
 * Every task carries the fields the list table needs (quotation, company,
 * category, target rate, assignedBy/assignedTo, status) AND the richer
 * product-detail fields the Pro-Bucket-style detail screen renders
 * (variants, images, supplier rates, classification, etc.).
 */

const daysAgo = (n) => {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString();
};

const supplierRate = (name, phone, rate, gst, discount, unit, remark) => ({
  _id: `rate-${name}-${rate}`.replace(/\s+/g, "-").toLowerCase(),
  supplier: { name, phone_1: phone, shopname: `${name} Traders` },
  rate,
  gstPercentage: gst,
  discountPercentage: discount,
  unit,
  remark,
  submittedAt: daysAgo(Math.floor(Math.random() * 6) + 1),
});

/**
 * Build one demo task. `overrides` lets each caller set the bits that decide
 * its bucket (status / assignedBy / assignedTo) and its identity.
 */
const makeTask = ({
  id,
  quotationCode,
  company,
  area,
  productName,
  extraProducts = [],
  category,
  group,
  subCategory,
  targetRate,
  procurementRate = null,
  status,
  assignedBy = null,
  assignedTo = null,
  createdAt,
  quantity,
  unit,
  hsnNumber,
  gstPercentage,
  modelNumber,
  description,
  remark,
  variants = [],
  rates = [],
  bucketType = "local",
}) => ({
  _id: id,
  id,
  type: "procurement",
  priority: "normal",
  status,
  assignedBy,
  assignedTo,
  productCategory: category,
  productGroup: group,
  subCategory,
  targetRate,
  procurementRate,
  supplierRateRemark: remark,
  createdAt,
  updatedAt: createdAt,
  dueDate: daysAgo(-5),
  bucketType,
  // detail-only enrichments
  productName,
  modelNumber,
  quantity,
  unit,
  hsnNumber,
  gstPercentage,
  description,
  variants,
  images: [],
  categoryName: category,
  groupName: group,
  rates,
  quotationId: {
    quotationCode,
    status: "approved",
    companyInfo: { name: company, area },
    customerName: company,
    companyName: company,
    products: [
      {
        _id: `${id}-p0`,
        productName,
        quantity,
        unit,
        hsnNumber,
        modelNumber,
      },
      ...extraProducts.map((p, i) => ({ _id: `${id}-p${i + 1}`, ...p })),
    ],
  },
});

